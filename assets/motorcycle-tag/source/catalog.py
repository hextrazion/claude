# Tier by price: free bikes are Starter, then each tier starts at its floor.
TIERS = [(1, "Common"), (25000, "Rare"), (150000, "Epic"), (800000, "Legendary")]
TIER_NAMES = ["Starter"] + [label for _, label in TIERS]


def tier(price):
    name = "Starter"
    for floor, label in TIERS:
        if price >= floor:
            name = label
    return name


def entries():
    out = []
    for brand, model, colour, base, skin, price, bonus in BIKES:
        b = BASES[base]
        stats = {k: min(10, v + (bonus if k == "Speed" else 0)) for k, v in b["stats"].items()}
        bike_id = "_".join([brand, model, colour]).lower().replace(" ", "_").replace("-", "")
        folder = b["folder"]
        out.append(dict(id=bike_id, name=f"{brand} {model} {colour}", brand=brand, model=model, colorway=colour, base=base,
                        skin=skin, skinFile=os.path.normpath(os.path.join(folder, "skins", f"{skin}.png")),
                        thumbnail=f"catalog/thumbnails/{bike_id}.png", price=price, tier=tier(price), stats=stats))
    return out


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(bikes, path):
    lines = [
        "-- BikeCatalog (ModuleScript), generated by assets/motorcycle-tag/source/catalog.py. Edit the Python and regenerate,",
        "-- or edit here if you prefer. Every bike is a base model (in your Bikes folder) wearing one skin texture.",
        "--",
        "-- After uploading each skin PNG (Asset Manager -> Bulk Import), paste its id into TextureId, e.g.",
        '--   TextureId = "rbxassetid://1234567890"',
        "-- Thumbnails (catalog/thumbnails/*.png) go into ThumbnailId the same way, for shop ImageLabels.",
        "--",
        "-- Usage (server):",
        "--   local BikeCatalog = require(game.ServerStorage.BikeCatalog)",
        "--   local bike = BikeCatalog.Spawn(\"halvex_hx6_apex\", game.ServerStorage.Bikes)",
        "--   bike.Parent = workspace",
        "-- Spawn needs the MotorcycleRig ModuleScript next to this one.",
        "",
        "local BikeCatalog = {}",
        "",
        "BikeCatalog.Bikes = {",
    ]
    for b in bikes:
        stats = ", ".join(f"{k} = {v}" for k, v in b["stats"].items())
        lines += [
            "\t{",
            f"\t\tId = {lua_string(b['id'])},",
            f"\t\tName = {lua_string(b['name'])},",
            f"\t\tBrand = {lua_string(b['brand'])},",
            f"\t\tBase = {lua_string(b['base'])},",
            f"\t\tSkin = {lua_string(b['skinFile'])},",
            f"\t\tPrice = {b['price']},",
            f"\t\tTier = {lua_string(b['tier'])},",
            f"\t\tStats = {{ {stats} }},",
            '\t\tTextureId = "",',
            '\t\tThumbnailId = "",',
            "\t},",
        ]
    lines += [
        "}",
        "",
        "BikeCatalog.ById = {}",
        "for _, bike in ipairs(BikeCatalog.Bikes) do",
        "\tBikeCatalog.ById[bike.Id] = bike",
        "end",
        "",
        "function BikeCatalog.Get(id)",
        "\treturn BikeCatalog.ById[id]",
        "end",
        "",
        "-- Bikes of one tier, or of one base model, in catalog (price) order.",
        "function BikeCatalog.Filter(field, value)",
        "\tlocal out = {}",
        "\tfor _, bike in ipairs(BikeCatalog.Bikes) do",
        "\t\tif bike[field] == value then",
        "\t\t\ttable.insert(out, bike)",
        "\t\tend",
        "\tend",
        "\treturn out",
        "end",
        "",
        "-- Clones the bike's base model from bikesFolder, names it after the catalog bike, applies its",
        "-- skin (once TextureId is filled in) and rigs it. Returns the unparented model.",
        "function BikeCatalog.Spawn(id, bikesFolder)",
        "\tlocal bike = BikeCatalog.ById[id]",
        "\tif not bike then",
        "\t\terror((\"BikeCatalog: unknown bike %q\"):format(tostring(id)), 2)",
        "\tend",
        "\tlocal template = bikesFolder:FindFirstChild(bike.Base)",
        "\tif not template then",
        "\t\terror((\"BikeCatalog: %s has no base model %q\"):format(bikesFolder:GetFullName(), bike.Base), 2)",
        "\tend",
        "\tlocal MotorcycleRig = require(script.Parent.MotorcycleRig)",
        "\tlocal model = template:Clone()",
        "\tmodel:SetAttribute(\"BikeId\", bike.Id)",
        "\tmodel:SetAttribute(\"SteeringRake\", MotorcycleRig.RAKE_BY_MODEL[bike.Base])",
        "\tmodel.Name = bike.Name",
        "\tif bike.TextureId ~= \"\" then",
        "\t\tMotorcycleRig.SetSkin(model, bike.TextureId)",
        "\tend",
        "\tMotorcycleRig.Rig(model)",
        "\treturn model",
        "end",
        "",
        "return BikeCatalog",
        "",
    ]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def write_render_jobs(bikes, path):
    jobs = []
    for b in bikes:
        base = BASES[b["base"]]
        folder = base["folder"]
        jobs.append(dict(id=b["id"], model=os.path.normpath(os.path.join(folder, b["base"] + ".glb")),
                         skin=b["skinFile"], rake=base["rake"], steer=base["steer"], camera=base["camera"],
                         out=b["thumbnail"]))
    with open(path, "w") as fh:
        json.dump(jobs, fh, indent=1)


def money(price):
    return "FREE" if price == 0 else f"${price:,}"


TIER_COLOURS = {"Starter": (190, 196, 204), "Common": (120, 200, 255), "Rare": (90, 225, 120), "Epic": (190, 120, 255),
                "Legendary": (255, 190, 50)}


def trim_thumbnail(path, aspect=4 / 3, margin=0.06):
    """Crop a rendered thumbnail to the bike (plus its shadow) and re-centre it at a fixed aspect."""
    im = Image.open(path).convert("RGBA")
    box = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    if not box:
        return
    w, h = box[2] - box[0], box[3] - box[1]
    w, h = w * (1 + 2 * margin), h * (1 + 2 * margin)
    w, h = max(w, h * aspect), max(h, w / aspect)
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    crop = im.crop((round(cx - w / 2), round(cy - h / 2), round(cx + w / 2), round(cy + h / 2)))
    crop.resize((512, 384), Image.LANCZOS).save(path)


def write_sheet(bikes, path, cols=4, card=(360, 300)):
    """Shop-style overview of every bike, like a garage menu."""
    pad = 18
    rows = -(-len(bikes) // cols)
    W, H = cols * (card[0] + pad) + pad, rows * (card[1] + pad) + pad
    sheet = Image.new("RGB", (W, H), (14, 15, 18))
    d = ImageDraw.Draw(sheet)
    for i, b in enumerate(bikes):
        x = pad + (i % cols) * (card[0] + pad)
        y = pad + (i // cols) * (card[1] + pad)
        d.rounded_rectangle([x, y, x + card[0], y + card[1]], 16, fill=(48, 50, 56), outline=(110, 114, 122), width=3)
        thumb_path = os.path.join(ROOT, b["thumbnail"])
        if os.path.exists(thumb_path):
            t = Image.open(thumb_path).convert("RGBA")
            t.thumbnail((card[0] - 40, card[1] - 96))
            sheet.paste(t, (x + (card[0] - t.width) // 2, y + 44), t)
        size = 20
        while size > 12 and d.textlength(b["name"], font=font(size)) > card[0] - 32:
            size -= 1
        d.text((x + 16, y + 14), b["name"], fill=(232, 234, 238), font=font(size))
        d.text((x + 16, y + card[1] - 42), money(b["price"]), fill=(110, 230, 110), font=font(24))
        d.text((x + card[0] - 16, y + card[1] - 38), b["tier"].upper(), fill=TIER_COLOURS[b["tier"]], font=font(15),
               anchor="ra")
    sheet.save(path)


def main():
    bikes = entries()
    os.makedirs(os.path.join(CATALOG_DIR, "thumbnails"), exist_ok=True)
    with open(os.path.join(CATALOG_DIR, "catalog.json"), "w") as fh:
        json.dump(bikes, fh, indent=1)
    write_lua(bikes, os.path.join(ROOT, "roblox", "BikeCatalog.lua"))
    write_render_jobs(bikes, os.path.join(CATALOG_DIR, "render_jobs.json"))
    missing = [b["skinFile"] for b in bikes if not os.path.exists(os.path.join(ROOT, b["skinFile"]))]
    if missing:
        sys.exit("missing skins (run the bike build scripts): " + ", ".join(missing))
    if "--sheet" in sys.argv:  # after rendering: trim the thumbnails, then lay out the garage sheet
        for b in bikes:
            trim_thumbnail(os.path.join(ROOT, b["thumbnail"]))
        write_sheet(bikes, os.path.join(CATALOG_DIR, "catalog_sheet.png"))
    print(f"{len(bikes)} bikes across {len(BASES)} base models")
    for name in TIER_NAMES:
        print(f"  {name:9s} {sum(1 for b in bikes if b['tier'] == name)}")


if __name__ == "__main__":
    main()
